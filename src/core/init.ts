import { appendFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { ScaffolderError } from './errors.js';
import {
  exists,
  LAST_RUN_FILE_NAME,
  SCAFFOLD_FOLDER_NAME,
  scaffoldingDir,
} from './paths.js';
import { listTemplateDirs } from './templates.js';
import type { IReporter } from './ports.js';

const EXAMPLE_CONFIG = `import { defineConfig } from 'template-scaffolder';

interface IAnswers {
  DESCRIPTION: string;
}

// Copy this folder to make a template of your own. See
// https://github.com/sheam/template-scaffolder/blob/main/docs/configuration.md
export default defineConfig<IAnswers>({
  name: 'Example',
  description: 'copy this folder to make your own template',
  prompts: [
    {
      name: 'DESCRIPTION',
      message: 'What does it do?',
      default: 'Something useful',
    },
  ],
  variables: ({ name }) => ({
    CAMEL_NAME: name.charAt(0).toLowerCase() + name.slice(1),
  }),
  // Fail on misspelled variables, and keep line breaks after inline macro calls.
  strictVariables: true,
  keepLineBreaks: true,
});
`;

const EXAMPLE_TEMPLATE = `#include(fileHeader.txt)
export function \${CAMEL_NAME}(): string {
  return '\${NAME}';
}
`;

const FILE_HEADER = `/**
 * $DESCRIPTION
 *
 * Generated by the $TEMPLATE_NAME template for $USERNAME.
 */`; // No final line break: it would add a blank line where the file is included.

const TSCONFIG = `{
  // Only for editor support: configs are run directly, without compiling.
  "compilerOptions": {
    "module": "NodeNext",
    "target": "ES2022",
    "strict": true,
    "noEmit": true,
    "skipLibCheck": true
  },
  "include": ["**/*.ts", "**/*.mts", "**/*.cts"]
}
`;

export interface IInitResult {
  /** Files created (or that would be, in a dry run), relative to the project root. */
  created: string[];
  /** True if the last-run file was added to .gitignore. */
  updatedGitignore: boolean;
}

/** Create `scaffolding/` with an example template. Refuses if templates already exist. */
export async function initScaffolding(options: {
  projectRoot: string;
  dryRun: boolean;
  reporter: IReporter;
}): Promise<IInitResult> {
  const { projectRoot, dryRun, reporter } = options;
  const dir = scaffoldingDir(projectRoot);
  if ((await exists(dir)) && (await listTemplateDirs(projectRoot)).length) {
    throw new ScaffolderError(
      'INIT_REFUSED',
      `${SCAFFOLD_FOLDER_NAME}/ already has templates. Copy one of them to start another.`
    );
  }

  const files: Record<string, string> = {
    'tsconfig.json': TSCONFIG,
    '_includes/fileHeader.txt': FILE_HEADER,
    'example/scaffolding.config.ts': EXAMPLE_CONFIG,
    'example/${NAME}.ts': EXAMPLE_TEMPLATE,
  };
  const created: string[] = [];
  for (const [file, content] of Object.entries(files)) {
    const target = path.join(dir, file);
    const relative = `${SCAFFOLD_FOLDER_NAME}/${file}`;
    if (await exists(target)) {
      reporter.info(`  exists   ${relative}`);
      continue;
    }
    if (!dryRun) {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content);
    }
    reporter.info(`  ${dryRun ? 'would create' : 'created'}  ${relative}`);
    created.push(relative);
  }

  const updatedGitignore = await ignoreLastRunFile(projectRoot, dryRun);
  if (updatedGitignore) {
    reporter.info(
      `  ${dryRun ? 'would update' : 'updated'}  .gitignore (add ${LAST_RUN_FILE_NAME})`
    );
  }
  return { created, updatedGitignore };
}

/** Each developer has their own last-run file; keep it out of git if there is a .gitignore. */
async function ignoreLastRunFile(
  projectRoot: string,
  dryRun: boolean
): Promise<boolean> {
  const gitignore = path.join(projectRoot, '.gitignore');
  if (!(await exists(gitignore))) return false;
  const text = await readFile(gitignore, 'utf-8');
  if (text.split(/\r?\n/).some(l => l.trim() === LAST_RUN_FILE_NAME))
    return false;
  if (!dryRun) {
    const prefix = text === '' || text.endsWith('\n') ? '' : '\n';
    await appendFile(gitignore, `${prefix}${LAST_RUN_FILE_NAME}\n`);
  }
  return true;
}
